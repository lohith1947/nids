"""
Stage 11.8.7 — Capture Listener
=================================

Passive packet capture on an isolated non-loopback interface.

This script runs on NIDS-VM and captures real attack traffic generated by
the Kali attacker over the VirtualBox Host-Only network.

It does NOT generate traffic. It does NOT start attack servers.
It only captures, optionally runs the NIDS pipeline, and writes results.

Architecture:
  Kali (192.168.56.105) --[attack traffic]--> NIDS-VM (192.168.56.107, enp0s8)
       |
       v
  capture_listener_11_8_7.py --[Scapy sniff on enp0s8]--> PCAP + JSONL dataset

Usage:
  # Capture only (raw PCAP):
  python -m NIDS.evaluation.capture_listener_11_8_7 --interface enp0s8 --output /tmp/stage11_8_7.pcap

  # Capture + NIDS pipeline evaluation:
  python -m NIDS.evaluation.capture_listener_11_8_7 \
    --interface enp0s8 \
    --output /tmp/stage11_8_7_dataset.jsonl \
    --pcap /tmp/stage11_8_7_raw.pcap \
    --run-pipeline

  # Stop capture cleanly:
  kill -INT <pid>
"""

import os
import sys
import json
